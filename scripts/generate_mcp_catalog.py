#!/usr/bin/env python3
"""Generate the offline MCP catalog from the validated package registry."""

from __future__ import annotations

import argparse
from collections import Counter
from pathlib import Path
import sys
from typing import get_args

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from agenthound.discovery.profile_registry import load_profiles  # noqa: E402
from agenthound.discovery.profiles import legacy_fields  # noqa: E402
from agenthound.models.claims import Action, Resource  # noqa: E402


def cell(value: str) -> str:
    """Preserve table structure without interpreting source text as HTML."""
    return (
        value.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace("|", "&#124;")
        .replace("\r", " ")
        .replace("\n", " ")
    )


def code(value: str) -> str:
    return "`" + cell(value).replace("`", "&#96;") + "`"


def table(headers: tuple[str, ...], rows: list[tuple[str, ...]]) -> list[str]:
    return [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
        *("| " + " | ".join(row) + " |" for row in rows),
    ]


def render_catalog() -> str:
    profiles = sorted(load_profiles(), key=lambda item: item.canonical_id)
    statuses = Counter(profile.status for profile in profiles)
    categories = Counter(profile.category for profile in profiles)
    claims = [claim for profile in profiles for claim in profile.claims]
    actions = Counter(f"{claim.resource}/{claim.action}" for claim in claims)
    action_profiles: Counter[str] = Counter()
    for profile in profiles:
        action_profiles.update(
            {f"{claim.resource}/{claim.action}" for claim in profile.claims}
        )
    lines = [
        "# MCP profile catalog",
        "",
        "Generated by `scripts/generate_mcp_catalog.py` from the validated "
        "bundled registry. Edit registry records, then regenerate this file.",
        "",
        f"{len(profiles)} distinct implementations; {len(claims)} capability claims. "
        "Aliases, versions and distribution formats do not increase the count. "
        "Verification dates describe static source review, not a runtime test.",
        "",
        "See [methodology](mcp-profile-methodology.md) for matching rules, "
        "confidence meanings, graph limits and verification procedure.",
        "",
        "## Status",
        "",
    ]
    lines.extend(
        table(
            ("Status", "Profiles"),
            [
                (code(status), str(statuses[status]))
                for status in ("verified", "recognized_only", "experimental")
            ],
        )
    )
    lines.extend(["", "## Categories", ""])
    lines.extend(
        table(
            ("Category", "Profiles"),
            [
                (cell(category), str(count))
                for category, count in sorted(categories.items())
            ],
        )
    )
    lines.extend(["", "## Resource and action coverage", ""])
    lines.extend(
        table(
            ("Resource/action", "Claims", "Profiles"),
            [
                (code(key), str(count), str(action_profiles[key]))
                for key, count in sorted(actions.items())
            ],
        )
    )
    lines.extend(["", "## Legacy dimension projection", ""])
    rows = []
    for dimension in ("file_access", "shell_exec", "network_send", "git_write"):
        matching_claims = sum(
            legacy_fields((claim,))[dimension] != "none" for claim in claims
        )
        matching_profiles = sum(
            legacy_fields(profile.claims)[dimension] != "none" for profile in profiles
        )
        rows.append((code(dimension), str(matching_profiles), str(matching_claims)))
    lines.extend(table(("Dimension", "Profiles", "Claims"), rows))
    lines.extend(
        [
            "",
            "A projected implementation dimension does not establish effective access "
            "to any asset. Domain claims without an equivalent legacy dimension stay "
            "in the normalized claim list.",
            "",
            "## Taxonomy",
            "",
            "Resources: "
            + ", ".join(code(value) for value in get_args(Resource))
            + ".",
            "",
            "Actions: " + ", ".join(code(value) for value in get_args(Action)) + ".",
            "",
            "## Profiles",
            "",
            "Claims show implementation confidence, verification status, scope, "
            "locality and read-only status. `ro=no` records an operation that can "
            "change state or whose implementation is not guaranteed read-only; it "
            "does not prove write authorization. References point to the reviewed "
            "official source or exact tool specification.",
            "",
        ]
    )
    rows = []
    for profile in profiles:
        launch = []
        launch.extend(
            f"{'npx / bunx' if profile.package_ecosystems[package] == 'npm' else 'uvx / pipx run'}: {code(package)}"
            for package in profile.packages
        )
        launch.extend("executable: " + code(value) for value in profile.executables)
        launch.extend("python -m: " + code(value) for value in profile.modules)
        launch.extend("docker run: " + code(value) for value in profile.containers)
        launch.extend("remote: " + code(value) for value in profile.endpoints)
        launch.extend("official alias: " + code(value) for value in profile.aliases)
        launch.extend(
            "historical compatibility alias (suspected): " + code(value)
            for value in profile.compatibility_aliases
        )
        claim_text = []
        for claim in profile.claims:
            label = f"{claim.resource}/{claim.action}"
            claim_text.append(
                f"[{code(label)}]({claim.source_url}) "
                f"({claim.confidence}; {claim.verification_status}; "
                f"ro={'yes' if claim.readonly else 'no'}; {claim.locality}; "
                f"scope={code(claim.scope)}) via "
                + ", ".join(code(tool) for tool in claim.tools)
                + ": "
                + cell(claim.evidence)
            )
        sources = [
            f"[repository]({profile.repository_url})",
            f"[documentation]({profile.documentation_url})",
        ]
        sources.extend(
            f"[identity {index}]({evidence.source_url}): {cell(evidence.evidence)}"
            for index, evidence in enumerate(profile.identity_sources, start=1)
        )
        rows.append(
            (
                cell(profile.display_name) + "<br>" + code(profile.canonical_id),
                cell(profile.maintainer) + "<br>" + cell(profile.category),
                "<br>".join(launch),
                code(profile.status)
                + "<br>"
                + ("<br>".join(claim_text) or "No capability claim."),
                "<br>".join(sources) + "<br>ref: " + code(profile.verified_ref),
                "<br>".join(cell(value) for value in profile.limitations),
                str(profile.verified_date),
            )
        )
    lines.extend(
        table(
            (
                "Name / canonical identity",
                "Maintainer / category",
                "Recognized launch identities",
                "Status / capability claims",
                "Official evidence",
                "Limitations",
                "Verified date",
            ),
            rows,
        )
    )
    lines.extend(["", "Do not edit this generated file by hand.", ""])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output", type=Path, default=ROOT / "docs" / "mcp-profile-catalog.md"
    )
    parser.add_argument("--check", action="store_true", help="fail if output differs")
    args = parser.parse_args()
    expected = render_catalog()
    if args.check:
        if (
            not args.output.exists()
            or args.output.read_text(encoding="utf-8") != expected
        ):
            print(f"MCP catalog is out of date: {args.output}", file=sys.stderr)
            return 1
        print(f"MCP catalog is current: {args.output}")
        return 0
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(expected, encoding="utf-8")
    print(f"Generated MCP catalog: {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
